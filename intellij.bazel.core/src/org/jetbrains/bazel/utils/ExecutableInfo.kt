package org.jetbrains.bazel.utils

import org.jetbrains.annotations.ApiStatus
import java.io.IOException
import java.nio.file.Path
import kotlin.io.path.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.readText

@ApiStatus.Internal
data class ExecutableInfo(
  val binary: Path,
  val workingDir: Path,
  val args: List<String>,
  val envVars: Map<String, String>,
  val directoriesToCreate: List<Path> = emptyList(),
) {
  fun createRequiredDirectories() {
    for (directory in directoriesToCreate) {
      directory.createDirectories()
    }
  }

  companion object {
    /**
     * Parses the content of the run script generated by `bazel run --script_path` into the [ExecutableInfo] needed to attach a native debugger.
     * The script is a Bash script, or a `cmd` script on Windows. For a test, the script starts a test wrapper:
     * [test-setup.sh](https://github.com/bazelbuild/bazel/blob/master/tools/test/test-setup.sh), or
     * [tw.exe](https://github.com/bazelbuild/bazel/blob/master/tools/test/windows/tw.cc) on Windows.
     * The debugger starts the test binary directly, so this function applies the environment changes of the test wrapper.
     */
    @Throws(UnexpectedScriptContentException::class)
    fun fromBazelRunScript(scriptContent: String): ExecutableInfo {
      // Bazel 9.2 and earlier write no newline after the last line, later versions write one.
      val content = scriptContent.removeSuffix("\n")
      val script = if (content.startsWith("#!")) parseBashScript(content) else parseCmdScript(content)
      return if (TEST_SRCDIR in script.env) script.toTestExecutableInfo() else script.toBinaryExecutableInfo()
    }
  }
}

private class ScriptPathContent(
  val execRoot: Path,
  val env: Map<String, String>,
  val command: List<String>,
  val pathSeparator: Char,
)

/**
 * Parses a script of this form:
 * ```
 * #!/bin/bash
 * cd <dir> && \
 *   exec env \
 *     -u <NAME> \
 *     <NAME>=<value> \
 *   <command> "$@"
 * ```
 */
private fun parseBashScript(content: String): ScriptPathContent {
  val lines = content.lines()
  if (lines.size < 4) throw UnexpectedScriptContentException("Expected at least 4 lines, actual: $lines")
  // lines[0] is `#!/bin/bash`
  val cdLine = parseBashWords(lines[1].removeSuffix("\\"))
  if (cdLine.size < 2 || cdLine[0] != "cd") throw UnexpectedScriptContentException("Unable to read execution root from script.")
  // lines[2] is `exec env \`
  val env = lines.subList(3, lines.lastIndex)
    .map { parseBashWords(it.removeSuffix("\\")) }
    .filter { it.firstOrNull() != "-u" }
    .associate { words ->
      val assignment = words.singleOrNull() ?: throw UnexpectedScriptContentException("Expected one env var per line, actual: $words")
      parseEnvAssignment(assignment)
    }
  return ScriptPathContent(Path(cdLine[1]), env, parseBashWords(lines.last()).dropLast(1), ':')
}

private fun parseEnvAssignment(assignment: String): Pair<String, String> {
  val parts = assignment.split('=', limit = 2)
  if (parts.size != 2) throw UnexpectedScriptContentException("Expected <NAME>=<value>, actual: $assignment")
  return parts[0] to parts[1]
}

/**
 * Parses a script of this form:
 * ```
 * @echo off
 *   cd /d <dir>
 *   SET <NAME>=
 *   SET <NAME>=<value>
 *   <command> %*
 * ```
 */
private fun parseCmdScript(content: String): ScriptPathContent {
  val lines = content.lines().map { it.trimStart() }
  if (lines.size < 3) throw UnexpectedScriptContentException("Expected at least 3 lines, actual: ${lines.size}")
  // lines[0] is `@echo off`
  if (!lines[1].startsWith("cd /d ")) throw UnexpectedScriptContentException("Unable to read execution root from script.")
  val env = mutableMapOf<String, String>()
  for (line in lines.subList(2, lines.lastIndex)) {
    if (!line.startsWith("SET ")) continue
    val (name, value) = parseEnvAssignment(line.removePrefix("SET "))
    if (value.isEmpty()) env.remove(name) else env[name] = value
  }
  return ScriptPathContent(Path(lines[1].removePrefix("cd /d ")), env, parseCmdWords(lines.last()).dropLast(1), ';')
}

private fun ScriptPathContent.toBinaryExecutableInfo(): ExecutableInfo {
  if (command.isEmpty()) throw UnexpectedScriptContentException("Expected an executable for regular binary.")
  return ExecutableInfo(
    binary = Path(command[0]),
    workingDir = execRoot,
    args = command.drop(1),
    envVars = env,
  )
}

// See https://github.com/bazelbuild/bazel/blob/master/tools/test/test-setup.sh
private fun ScriptPathContent.toTestExecutableInfo(): ExecutableInfo {
  if (command.size < 2) throw UnexpectedScriptContentException("Expected at least 2 arguments for test binary, actual: $command")
  val workspaceName = env[TEST_WORKSPACE] ?: throw UnexpectedScriptContentException("Unable to read workspace name from script.")

  val testEnv = env.toMutableMap()
  testEnv["BAZEL_TEST"] = "1"
  for (name in relativePathVarsToResolve) {
    testEnv.computeIfPresent(name) { _, value -> execRoot.resolve(value).toString() }
  }
  testEnv.keys.removeAll(varsToUnset)
  testEnv[TEST_TMPDIR]?.let { testEnv["GTEST_TMP_DIR"] = it }
  testEnv["PATH"]?.let { testEnv["PATH"] = ".$pathSeparator$it" }

  val testSrcDir = Path(testEnv.getValue(TEST_SRCDIR))
  // A test in an external repository is ../<repo>/<path>
  val runfilePath = if (command[1].startsWith("../")) command[1].removePrefix("../") else "$workspaceName/${command[1]}"
  val binary = if (testEnv["RUNFILES_MANIFEST_ONLY"] == "1") {
    val manifest = testSrcDir.resolve("MANIFEST")
    testEnv["RUNFILES_MANIFEST_FILE"] = manifest.toString()
    val manifestContent = try {
      manifest.readText()
    }
    catch (e: IOException) {
      throw UnexpectedScriptContentException("Unable to read the runfiles manifest $manifest: ${e.message}")
    }
    // Each manifest line is `<runfile path> <target path>`.
    val target = manifestContent.lines().firstOrNull { it.startsWith("$runfilePath ") }
                 ?: throw UnexpectedScriptContentException("Unable to find $runfilePath in the runfiles manifest $manifest.")
    Path(target.removePrefix("$runfilePath "))
  }
  else {
    testSrcDir.resolve(runfilePath)
  }

  return ExecutableInfo(
    binary = binary,
    workingDir = if (env["RUNTEST_PRESERVE_CWD"].isNullOrEmpty()) testSrcDir.resolve(workspaceName) else execRoot,
    args = command.drop(2),  // tests go through the wrapper script, so <wrapper> <binary> arg0 ... argN
    envVars = testEnv,
    directoriesToCreate = listOfNotNull(
      testEnv[TEST_TMPDIR]?.let { Path(it) },
      testEnv[TEST_UNDECLARED_OUTPUTS_DIR]?.let { Path(it) },
      testEnv[TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR]?.let { Path(it) },
      testEnv[XML_OUTPUT_FILE]?.let { Path(it) }?.parent,
    ),
  )
}

private fun parseBashWords(line: String): List<String> {
  val words = mutableListOf<String>()
  val word = StringBuilder()
  var inWord = false
  var inQuotes = false
  var escaped = false
  for (char in line) {
    when {
      escaped -> {
        word.append(char)
        escaped = false
      }

      inQuotes -> if (char == '\'') inQuotes = false else word.append(char)
      char == '\'' -> {
        inQuotes = true
        inWord = true
      }

      char == '\\' -> {
        escaped = true
        inWord = true
      }

      char == ' ' -> {
        if (inWord) words += word.toString()
        word.clear()
        inWord = false
      }

      else -> {
        word.append(char)
        inWord = true
      }
    }
  }
  if (inQuotes) throw UnexpectedScriptContentException("Unterminated quote: $line")
  if (inWord) words += word.toString()
  return words
}

private fun parseCmdWords(line: String): List<String> {
  val words = mutableListOf<String>()
  val word = StringBuilder()
  var inWord = false
  var inQuotes = false
  var backslashes = 0
  for (char in line) {
    if (char == '\\') {
      backslashes++
      inWord = true
      continue
    }
    if (char == '"') {
      word.append("\\".repeat(backslashes / 2))
      if (backslashes % 2 == 1) word.append('"') else inQuotes = !inQuotes
      inWord = true
    }
    else {
      word.append("\\".repeat(backslashes))
      if (char == ' ' && !inQuotes) {
        if (inWord) words += word.toString()
        word.clear()
        inWord = false
      }
      else {
        word.append(char)
        inWord = true
      }
    }
    backslashes = 0
  }
  word.append("\\".repeat(backslashes))
  if (inQuotes) throw UnexpectedScriptContentException("Unterminated quote: $line")
  if (inWord) words += word.toString()
  return words
}

@ApiStatus.Internal
class UnexpectedScriptContentException(reason: String) : Exception("Failed to parse Bazel run script. Reason: $reason")

private const val TEST_SRCDIR = "TEST_SRCDIR"
private const val TEST_WORKSPACE = "TEST_WORKSPACE"
private const val TEST_TMPDIR = "TEST_TMPDIR"
private const val XML_OUTPUT_FILE = "XML_OUTPUT_FILE"
private const val TEST_UNDECLARED_OUTPUTS_DIR = "TEST_UNDECLARED_OUTPUTS_DIR"
private const val TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR = "TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR"

private val relativePathVarsToResolve = listOf(
  TEST_SRCDIR,
  TEST_TMPDIR,
  XML_OUTPUT_FILE,
  TEST_UNDECLARED_OUTPUTS_DIR,
  TEST_UNDECLARED_OUTPUTS_ANNOTATIONS_DIR,
  "TEST_PREMATURE_EXIT_FILE",
  "TEST_WARNINGS_OUTPUT_FILE",
  "TEST_LOGSPLITTER_OUTPUT_FILE",
  "TEST_INFRASTRUCTURE_FAILURE_FILE",
  "TEST_UNUSED_RUNFILES_LOG_FILE",
  "RUNFILES_DIR",
  "JAVA_RUNFILES",
  "PYTHON_RUNFILES",
  "HOME",
)

private val varsToUnset = listOf(
  "TEST_UNDECLARED_OUTPUTS_MANIFEST",
  "TEST_UNDECLARED_OUTPUTS_ZIP",
  "TEST_UNDECLARED_OUTPUTS_ANNOTATIONS",
)
